"""Build the compact, file://-only asset bundle used to keep canvas export origin-clean."""

from __future__ import annotations

import base64
import io
import json
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "js" / "offline-export-assets.js"
ASSET_FOLDERS = ("surfaces", "crests", "seals")


def encode_webp(path: Path) -> str:
    with Image.open(path) as source:
        image = source.convert("RGBA")
        buffer = io.BytesIO()
        if path.parent.name == "surfaces":
            image.save(buffer, "WEBP", quality=92, method=4, exact=True)
        else:
            image.save(buffer, "WEBP", quality=96, method=4, exact=True)
    return "data:image/webp;base64," + base64.b64encode(buffer.getvalue()).decode("ascii")


def main() -> None:
    assets: dict[str, str] = {}
    for folder in ASSET_FOLDERS:
        for path in sorted((ROOT / "assets" / folder).rglob("*.png")):
            key = path.relative_to(ROOT).as_posix()
            assets[key] = encode_webp(path)

    payload = json.dumps(assets, separators=(",", ":"))
    OUTPUT.write_text(
        "// Generated by scripts/build-offline-export-assets.py. Physical assets remain authoritative.\n"
        "window.AnbennarEmbeddedAssets=Object.freeze(" + payload + ");\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUTPUT.name}: {len(assets)} assets, {OUTPUT.stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
